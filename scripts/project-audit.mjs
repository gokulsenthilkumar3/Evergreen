import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { updateReport } from './roadmap-audit.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ignored = new Set(['node_modules', 'dist', 'build', 'coverage', '.git', 'generated', 'backend', 'release', 'out']);
const source = /\.(?:[cm]?[jt]sx?|json|css|html|prisma|sql|ya?ml|sh|ps1|toml)$/;
const test = /(?:\.(?:spec|test)\.[cm]?[jt]sx?$|\/test\/.*\.ts$)/;
export function listSourceFiles(base, relative = '') {
  if (!existsSync(join(base, relative))) return [];
  return readdirSync(join(base, relative), { withFileTypes: true }).flatMap(entry => {
    const file = relative ? relative + '/' + entry.name : entry.name;
    if (entry.isSymbolicLink()) return [];
    if (entry.isDirectory()) return ignored.has(entry.name) ? [] : listSourceFiles(base, file);
    if (!entry.isFile() || entry.name.startsWith('.env') || /(?:package-lock|pnpm-lock|tsconfig\.tsbuildinfo)/.test(entry.name)) return [];
    return source.test(entry.name) || /^Dockerfile(?:\.|$)/.test(entry.name) ? [file] : [];
  }).sort();
}
export function renderSurface(base = root) {
  const workspaces = ['apps', 'packages'].flatMap(parent => readdirSync(join(base, parent), { withFileTypes: true })
    .filter(e => e.isDirectory() && existsSync(join(base, parent, e.name, 'package.json')))
    .map(e => parent + '/' + e.name)).sort();
  const inventories = [...workspaces, 'scripts', 'deploy', '.github', 'agent-system'].map(area => ({ area, files: listSourceFiles(base, area) }));
  inventories.push({ area: 'Root configuration', files: ['package.json', 'docker-compose.yml', 'docker-compose.production.yml'].filter(p => existsSync(join(base, p))) });
  const files = inventories.flatMap(i => i.files);
  const hash = createHash('sha256');
  for (const file of [...files].sort()) hash.update(file).update('\0').update(readFileSync(join(base, file), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n')).update('\0');
  const lines = ['# Project source surface', '',
    'Generated by npm run audit:surface. npm run audit:check detects drift. This inventories authored code/configuration, not line-by-line review or runtime correctness.', '',
    '- ' + workspaces.length + ' workspace manifests; ' + files.length + ' source/configuration files; ' + files.filter(f => test.test(f)).length + ' test/setup files.',
    '- Normalized source SHA-256: ' + hash.digest('hex') + '.',
    '- Includes scripts, deployment, CI and agent policies; excludes dependencies, generated output, secrets, local databases, archives and the packaged desktop backend copy.',
    '- Roadmap source presence is in [roadmap evidence](ROADMAP_EVIDENCE.md). Markdown links are checked by `npm run docs:check`; this inventory covers executable and configuration files.', '',
    '## Workspace checks', '', '| Workspace | Build | Tests | Lint |', '| --- | --- | --- | --- |'];
  for (const area of workspaces) {
    const scripts = JSON.parse(readFileSync(join(base, area, 'package.json'), 'utf8').replace(/^\uFEFF/, '')).scripts || {};
    lines.push('| ' + area + ' | ' + (scripts.build ? 'build' : 'No script') + ' | ' + (scripts.test ? 'test' : 'No script') + ' | ' + (scripts['lint:check'] ? 'lint:check' : scripts.lint ? 'lint' : 'No script') + ' |');
  }
  lines.push('', 'Use lint:check on APIs: their lint commands modify files. Missing workspace tests are coverage gaps, not passing checks.', '', '## Inventory', '', '| Area | Files | Test/setup files |', '| --- | --- | --- |');
  for (const { area, files: entries } of inventories) lines.push('| ' + area + ' | ' + entries.length + ' | ' + entries.filter(f => test.test(f)).length + ' |');
  for (const { area, files: entries } of inventories) {
    lines.push('', '### ' + area, '');
    lines.push(...entries.map(file => '- [' + file + '](../../' + file + ')' + (test.test(file) ? ' (test/setup)' : '')));
  }
  lines.push('', 'See [project audit](../PROJECT_AUDIT.md), [backlog](../IMPLEMENTATION_BACKLOG.md) and [runbook](../MAINTENANCE_RUNBOOK.md).', '');
  return lines.join('\n');
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  if (!check) mkdirSync(join(root, 'docs/reference'), { recursive: true });
  const current = updateReport(join(root, 'docs/reference/PROJECT_SURFACE.md'), renderSurface(), check);
  console.log(current ? 'Project source inventory is current.' : 'Project inventory is stale. Run npm run audit:surface.');
  if (!current) process.exitCode = 1;
}
