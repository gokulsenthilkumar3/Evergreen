import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const source = fs.readFileSync(path.join(root, 'packages/database/prisma/schema.prisma'), 'utf8');
// Unit prices/rates and physical quantities retain six decimal places. Posted monetary
// totals, payments and journal amounts are stored at paise precision.
export const monetaryFields = new Set(['totalCost', 'subtotal', 'cgst', 'sgst', 'igst', 'total', 'amountPaid',
  'creditTotal', 'amount', 'debit', 'credit', 'discount', 'processingCost', 'basicPay', 'netPay', 'monthlySalary']);
export function postgresSchema(sqliteSchema) {
  return '// Generated by scripts/data/postgres-schema.mjs; edit the canonical schema first.\n' + sqliteSchema
    .replace('provider = "prisma-client-js"', 'provider = "prisma-client-js"\n  output = "../../generated/postgres"')
    .replace('provider = "sqlite"', 'provider = "postgresql"')
    .replace(/^(\s*)(\w+)(\s+)Float(\??)([^\r\n]*)/gm, (_line, indent, field, spacing, nullable, rest) =>
      `${indent}${field}${spacing}Decimal${nullable} @db.Decimal(24, ${monetaryFields.has(field) ? 2 : 6})${rest}`);
}
const target = path.join(root, 'packages/database/prisma/postgres/schema.prisma');
const content = postgresSchema(source);
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
    console.error('PostgreSQL schema is stale. Run node scripts/data/postgres-schema.mjs');
    process.exitCode = 1;
  }
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
}
}
